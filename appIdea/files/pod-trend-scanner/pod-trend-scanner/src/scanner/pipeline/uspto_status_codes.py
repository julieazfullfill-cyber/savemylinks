def classify_case_status(status_code: str) -> StatusCategory:
    """LIVE/DEAD/UNKNOWN cho `case-file-header/status-code` (3 chữ số). Mặc định LIVE
    (fail-closed: chặn nếu không chắc là đã chết hẳn), trừ khi nằm trong danh sách
    DEAD/UNKNOWN đã liệt kê rõ ở trên. Mã lạ không có trong Table 1 (không nên xảy ra
    với dữ liệu bulk thật) -> UNKNOWN, không đoán."""
    code = status_code.strip().zfill(3)
    if code not in STATUS_CODE_DESCRIPTIONS:
        return "unknown"
    if code in _DEAD_CODES:
        return "dead"
    if code in _UNKNOWN_CODES:
        return "unknown"
    return "live"
